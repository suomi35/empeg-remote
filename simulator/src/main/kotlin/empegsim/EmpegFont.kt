    // 0x7f (DEL) has no glyph entry in the kernel source (zero-padded) -> blank
    fun glyph(ch: Char): IntArray =
        if (ch.code in FIRST_CHAR until LAST_CHAR) GLYPHS[ch.code - FIRST_CHAR] else BLANK

    val BLANK = intArrayOf(0, 0, 0, 0, 0, 0)

    /** Variable width: last column byte is inter-character spacing; trim empty
     *  glyph columns, mirroring hijack's draw_char. Space is fixed at 3 columns. */
    fun charWidth(ch: Char): Int {
        if (ch == ' ') return 3
        val g = glyph(ch)
        var numCols = MAX_WIDTH
        while (numCols > 2 && g[numCols - 2] == 0) numCols--
        return numCols
    }
